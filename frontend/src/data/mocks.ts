export function recognizeQuery(query: string): ScenarioId | undefined {
  const normalized = query.trim().toLowerCase().replace(/[–—]/g, "-");
  return promptIds.find(
    (id) =>
      scenarios[id].query.toLowerCase().replace(/[–—]/g, "-") === normalized,
  );
}
